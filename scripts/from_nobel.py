#!/usr/bin/env python3
"""Propose day records from the Nobel Prize's own API.

The prize's public API carries each laureate's birth date and the year and
citation of the award, and nobelprize.org is on the sources allowlist, so a
record built from it arrives already backed by a body of record rather than by
somebody's recollection.

This writes *candidates*. They carry no status; `verify_days.py` still fetches
every source and decides. The point of the generator is to stop a person typing
a hundred dates by hand, not to skip the gate.

Usage:
    from_nobel.py --category che --out data/_candidates-chemistry.yaml
                  [--max-per-month 6] [--limit 200]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import urllib.parse
import urllib.request

API = "https://api.nobelprize.org/2.1/laureates"
UA = "redletter-candidates/0.1 (+https://github.com/tjmustard/redletter)"

CATEGORIES = {"che": "Chemistry", "phy": "Physics", "med": "Physiology or Medicine"}


def get(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def laureates(category: str, limit: int):
    """Every laureate in a category, following the API's own paging."""
    out, offset = [], 0
    while len(out) < limit:
        page = min(100, limit - len(out))
        query = urllib.parse.urlencode({
            "nobelPrizeCategory": category, "limit": page, "offset": offset,
        })
        payload = get(f"{API}?{query}")
        batch = payload.get("laureates", [])
        out.extend(batch)
        if not batch or len(batch) < page:
            break
        offset += page
    return out[:limit]


def first_prize(laureate):
    """The earliest prize this laureate won: (year, motivation, category)."""
    prizes = laureate.get("nobelPrizes", [])
    if not prizes:
        return None
    prize = sorted(prizes, key=lambda p: p.get("awardYear", "9999"))[0]
    return {
        "year": prize.get("awardYear"),
        "motivation": (prize.get("motivation") or {}).get("en", ""),
    }


def shorten(text: str, limit: int = 150) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def to_day(laureate, index: int, category: str) -> dict | None:
    birth = (laureate.get("birth") or {}).get("date")
    prize = first_prize(laureate)
    if not birth or not prize:
        return None
    # The API writes 1943-00-00 when only the year is known. A day the calendar
    # cannot place is not a day.
    try:
        parsed = dt.date.fromisoformat(birth)
    except ValueError:
        return None
    name = (laureate.get("fullName") or laureate.get("knownName") or {}).get("en")
    if not name:
        return None
    year, month_day = birth[:4], birth[5:]
    place = ((laureate.get("birth") or {}).get("place") or {}).get("country", {}).get("en", "")
    where = f" in {place}" if place else ""
    return {
        "id": f"D-{category.upper()}-B{index:03d}",
        "month_day": month_day,
        "year": int(year),
        "kind": "birth",
        "title": f"{name} is born",
        "blurb": shorten(
            f"Nobel Prize in {CATEGORIES.get(category, category)} {prize['year']}{where}: "
            f"{prize['motivation']}"
        ) if prize["motivation"] else
        f"Nobel Prize in {CATEGORIES.get(category, category)} {prize['year']}{where}.",
        "date": {
            "as_recorded": birth,
            "calendar": "gregorian",
            "gregorian": birth,
            "precision": "day",
        },
        "sources": [{
            "type": "archive",
            "citation": f"Nobel Prize — {name}",
            "url": f"https://api.nobelprize.org/2.1/laureate/{laureate['id']}",
        }],
    }


def yaml_text(topic: dict, days) -> str:
    """A small writer, so candidates land in the same shape a person would type."""
    def q(value):
        s = str(value).replace("\\", "\\\\").replace('"', '\\"')
        return f'"{s}"'

    lines = [
        "# Generated by scripts/from_nobel.py — candidates, not a finished dataset.",
        "# Every one still goes through scripts/verify_days.py before it can print.",
        "",
        "topic:",
        f"  id: {topic['id']}",
        f"  title: {q(topic['title'])}",
        f"  scope: >-",
        f"    {topic['scope']}",
        f"  print_year: {topic['print_year']}",
        "  kinds: [birth, discovery, milestone, first, loss]",
        "",
        "days:",
    ]
    for d in days:
        lines += [
            f"  - id: {d['id']}",
            f"    month_day: {q(d['month_day'])}",
            f"    year: {d['year']}",
            f"    kind: {d['kind']}",
            f"    title: {q(d['title'])}",
            f"    blurb: >-",
            f"      {d['blurb']}",
            "    date:",
            f"      as_recorded: {d['date']['as_recorded']}",
            f"      calendar: gregorian",
            f"      gregorian: {d['date']['gregorian']}",
            f"      precision: day",
            "    sources:",
        ]
        for s in d["sources"]:
            lines += [
                f"      - type: {s['type']}",
                f"        citation: {q(s['citation'])}",
                f"        url: {s['url']}",
            ]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--category", default="che", choices=sorted(CATEGORIES))
    ap.add_argument("--out", required=True)
    ap.add_argument("--limit", type=int, default=200)
    ap.add_argument("--max-per-month", type=int, default=6,
                    help="keep the earliest laureates up to this many in each month")
    ap.add_argument("--print-year", type=int, default=2027)
    args = ap.parse_args()

    people = laureates(args.category, args.limit)
    days = []
    for laureate in people:
        day = to_day(laureate, len(days) + 1, args.category)
        if day:
            days.append(day)

    # Oldest first, then a spread: a calendar wants a few a month, not 40 in May.
    days.sort(key=lambda d: (int(d["year"]), d["month_day"]))
    per_month: dict[str, int] = {}
    kept = []
    for d in days:
        m = d["month_day"][:2]
        if per_month.get(m, 0) >= args.max_per_month:
            continue
        per_month[m] = per_month.get(m, 0) + 1
        kept.append(d)
    kept.sort(key=lambda d: d["month_day"])

    topic = {
        "id": f"{CATEGORIES[args.category].lower().replace(' ', '-')}",
        "title": f"{CATEGORIES[args.category]} — laureates",
        "scope": "People who won the Nobel Prize in this field, on the day they were born.",
        "print_year": args.print_year,
    }
    path = pathlib.Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml_text(topic, kept))

    print(f"{path}: {len(kept)} candidates from {len(people)} laureates")
    for m in range(1, 13):
        n = sum(1 for d in kept if d["month_day"][:2] == f"{m:02d}")
        print(f"  {m:02d}  {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
